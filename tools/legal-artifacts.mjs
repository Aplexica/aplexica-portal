import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const defaultOutput = path.join(root, 'dist-local', 'legal');
const artifactNames = ['LICENSE', 'NOTICE', 'THIRD_PARTY_NOTICES.txt', 'manifest.json'];

function sha256(value) {
  return `sha256-${createHash('sha256').update(value).digest('base64')}`;
}

function normalizedText(file) {
  const text = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
  return text.endsWith('\n') ? text : `${text}\n`;
}

function productionGraphKeys() {
  const raw = execFileSync('pnpm', ['list', '--prod', '--depth', 'Infinity', '--json'], {
    cwd: root,
    encoding: 'utf8',
  });
  const projects = JSON.parse(raw);
  const keys = new Set();
  const visit = (dependencies) => {
    for (const [name, dependency] of Object.entries(dependencies ?? {})) {
      keys.add(`${name}@${dependency.version}`);
      visit(dependency.dependencies);
      visit(dependency.optionalDependencies);
    }
  };
  for (const project of projects) visit(project.dependencies);
  return [...keys].sort();
}

function productionPackages() {
  const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
    cwd: root,
    encoding: 'utf8',
  });
  const inventory = JSON.parse(raw);
  const packages = new Map();

  for (const [license, records] of Object.entries(inventory)) {
    for (const record of records) {
      for (const packagePath of record.paths) {
        const metadata = JSON.parse(fs.readFileSync(path.join(packagePath, 'package.json'), 'utf8'));
        const key = `${metadata.name}@${metadata.version}`;
        const licenseFiles = fs.readdirSync(packagePath)
          .filter((name) => /^(licen[sc]e|copying|notice|copyright)(\.|$)/i.test(name))
          .sort((a, b) => a.localeCompare(b));
        if (licenseFiles.length === 0) {
          throw new Error(`${key} (${license}) has no distributable license/copyright file`);
        }

        const entry = {
          name: metadata.name,
          version: metadata.version,
          license,
          files: licenseFiles.map((name) => {
            const text = normalizedText(path.join(packagePath, name));
            return { name, text, sha256: sha256(text) };
          }),
        };
        const prior = packages.get(key);
        if (prior && JSON.stringify(prior) !== JSON.stringify(entry)) {
          throw new Error(`conflicting license metadata for ${key}`);
        }
        packages.set(key, entry);
      }
    }
  }

  const result = [...packages.values()].sort((a, b) =>
    a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
  const graphKeys = productionGraphKeys();
  const inventoryKeys = result.map((entry) => `${entry.name}@${entry.version}`).sort();
  const missing = graphKeys.filter((key) => !inventoryKeys.includes(key));
  const extra = inventoryKeys.filter((key) => !graphKeys.includes(key));
  if (missing.length > 0 || extra.length > 0) {
    throw new Error(`license inventory/production graph mismatch; missing=${missing.join(',')}; extra=${extra.join(',')}`);
  }
  return result;
}

function expectedArtifacts() {
  const projectLicense = normalizedText(path.join(root, 'LICENSE'));
  const projectNotice = normalizedText(path.join(root, 'NOTICE'));
  const lockfile = fs.readFileSync(path.join(root, 'pnpm-lock.yaml'));
  const packages = productionPackages();
  const sections = packages.map((entry) => {
    const files = entry.files.map((file) => [
      `--- ${file.name} (SHA-256 ${file.sha256}) ---`,
      file.text.trimEnd(),
    ].join('\n')).join('\n\n');
    return [
      '='.repeat(79),
      `${entry.name}@${entry.version}`,
      `SPDX license expression: ${entry.license}`,
      files,
    ].join('\n');
  });
  const thirdParty = [
    'Aplexica Portal — Third-Party Notices and License Texts',
    '',
    'This file is generated deterministically from the exact pnpm locked production',
    'dependency graph. It contains the applicable license/copyright files shipped',
    'by every installed production package. Do not edit this file by hand.',
    '',
    `pnpm-lock.yaml SHA-256: ${sha256(lockfile)}`,
    'Production graph command: pnpm list --prod --depth Infinity --json',
    'License inventory command: pnpm licenses list --prod --json',
    `Production package count: ${packages.length}`,
    '',
    ...sections,
    '',
  ].join('\n');
  const manifest = {
    formatVersion: 1,
    generator: 'tools/legal-artifacts.mjs',
    productionGraphCommand: 'pnpm list --prod --depth Infinity --json',
    licenseInventoryCommand: 'pnpm licenses list --prod --json',
    lockfileSha256: sha256(lockfile),
    project: {
      license: 'AGPL-3.0-or-later',
      licenseFile: 'LICENSE',
      licenseSha256: sha256(projectLicense),
      noticeFile: 'NOTICE',
      noticeSha256: sha256(projectNotice),
    },
    productionPackageCount: packages.length,
    packages: packages.map((entry) => ({
      name: entry.name,
      version: entry.version,
      license: entry.license,
      files: entry.files.map(({ name, sha256: digest }) => ({ name, sha256: digest })),
    })),
    thirdPartyNoticesSha256: sha256(thirdParty),
  };

  return new Map([
    ['LICENSE', projectLicense],
    ['NOTICE', projectNotice],
    ['THIRD_PARTY_NOTICES.txt', thirdParty],
    ['manifest.json', `${JSON.stringify(manifest, null, 2)}\n`],
  ]);
}

function generate(outputDir = defaultOutput) {
  const artifacts = expectedArtifacts();
  fs.mkdirSync(outputDir, { recursive: true });
  for (const [name, contents] of artifacts) fs.writeFileSync(path.join(outputDir, name), contents);
  return artifacts;
}

function check(outputDir = defaultOutput) {
  const expected = expectedArtifacts();
  const problems = [];
  for (const name of artifactNames) {
    const file = path.join(outputDir, name);
    if (!fs.existsSync(file)) {
      problems.push(`missing ${name}`);
      continue;
    }
    const actual = fs.readFileSync(file, 'utf8');
    if (actual !== expected.get(name)) problems.push(`stale or incomplete ${name}`);
  }
  const unexpected = fs.existsSync(outputDir)
    ? fs.readdirSync(outputDir).filter((name) => !artifactNames.includes(name)).sort()
    : [];
  if (unexpected.length > 0) problems.push(`unexpected legal artifacts: ${unexpected.join(', ')}`);
  if (problems.length > 0) throw new Error(problems.join('; '));
  return JSON.parse(expected.get('manifest.json'));
}

function selfTest() {
  const expected = expectedArtifacts();
  const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'aplexica-legal-negative-'));
  const negativeResults = [];
  try {
    const legalDir = path.join(tempRoot, 'legal');
    fs.mkdirSync(legalDir);
    for (const [name, contents] of expected) fs.writeFileSync(path.join(legalDir, name), contents);
    check(legalDir);

    const manifestFile = path.join(legalDir, 'manifest.json');
    const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
    manifest.packages.pop();
    manifest.productionPackageCount -= 1;
    fs.writeFileSync(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
    negativeResults.push(expectFailure(() => check(legalDir), 'missing production package'));

    fs.writeFileSync(manifestFile, expected.get('manifest.json'));
    fs.writeFileSync(path.join(legalDir, 'THIRD_PARTY_NOTICES.txt'), 'truncated\n');
    negativeResults.push(expectFailure(() => check(legalDir), 'truncated license text'));

    fs.writeFileSync(path.join(legalDir, 'THIRD_PARTY_NOTICES.txt'), expected.get('THIRD_PARTY_NOTICES.txt'));
    fs.unlinkSync(path.join(legalDir, 'NOTICE'));
    negativeResults.push(expectFailure(() => check(legalDir), 'missing project notice'));
  } finally {
    fs.rmSync(tempRoot, { recursive: true, force: true });
  }
  return negativeResults;
}

function expectFailure(operation, control) {
  try {
    operation();
  } catch (error) {
    return { control, rejected: true, reason: error instanceof Error ? error.message : String(error) };
  }
  throw new Error(`negative control unexpectedly passed: ${control}`);
}

const command = process.argv[2];
if (command === 'generate') {
  const artifacts = generate();
  console.log(JSON.stringify({ result: 'PASS', generated: [...artifacts.keys()], output: defaultOutput }, null, 2));
} else if (command === 'check') {
  const manifest = check();
  console.log(JSON.stringify({
    result: 'PASS',
    output: defaultOutput,
    productionPackageCount: manifest.productionPackageCount,
    lockfileSha256: manifest.lockfileSha256,
  }, null, 2));
} else if (command === 'self-test') {
  console.log(JSON.stringify({ result: 'PASS', negativeControls: selfTest() }, null, 2));
} else {
  console.error('usage: node tools/legal-artifacts.mjs <generate|check|self-test>');
  process.exit(2);
}
